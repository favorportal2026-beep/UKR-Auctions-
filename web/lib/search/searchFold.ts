/**
 * Згортає текст до нечутливої до написання форми ДЛЯ ПОШУКУ (не для показу).
 * Українські дані змішують ua/ru написання ("Жовтневий"/"Жовтневый"), а
 * користувач вводить будь-яке — тож матчинг має ігнорувати сплутувані родини
 * літер і шум апострофів/дефісів. Перетворення консервативне:
 * i-родина (і ї ы → и), e-родина (є э ё → е), ґ → г, прибирає ь/ъ та апострофи,
 * нормалізує роздільники. `й` лишається окремим, щоб не зливати різні слова.
 *
 * Портовано з RONDA (lib/search/searchFold.ts). ES5-safe: без /u та \p{}.
 */
export function foldSearchText(value: string | null | undefined): string {
  return (value ?? '')
    .toLowerCase()
    .replace(/[’ʼ'`´]/g, '')
    .replace(/[«»"“”„]/g, '')
    .replace(/[єэё]/g, 'е')
    .replace(/[іїы]/g, 'и')
    .replace(/ґ/g, 'г')
    .replace(/[ьъ]/g, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
